class PersistenceError(RuntimeError):
    code = "persistence.error"

    def __init__(self) -> None:
        super().__init__(self.code)


class NotFound(PersistenceError):
    code = "persistence.not_found"


class RevisionConflict(PersistenceError):
    code = "persistence.revision_conflict"


class IdempotencyConflict(PersistenceError):
    code = "persistence.idempotency_conflict"


class PersistenceUnavailable(PersistenceError):
    code = "persistence.unavailable"


class ReservationCapacityExceeded(PersistenceError):
    code = "reservation.capacity_exceeded"


